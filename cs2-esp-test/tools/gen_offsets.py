#!/usr/bin/env python3
"""
gen_offsets.py
--------------
Extracts the offsets/schemata used by the C++ diagnostic+ESP project straight
from the cs2-dumper JSON output (offsets.json + client_dll.json) and writes
two self-contained C++ headers:

  src/offsets.hpp   -> module-relative offsets (dw*), per module
  src/schema.hpp    -> class field offsets (m_*), relative to class instance

Why generate instead of copy-pasting: the values below are guaranteed to match
the dumped JSON exactly, so no transcription error can creep into the C++ side.

Usage (PowerShell, run from cs2-esp-test/):
    python tools/gen_offsets.py

The script expects the JSON files one directory above the project folder:
    ../offsets.json
    ../client_dll.json
    ../info.json   (informational only; build number is printed)
"""

import json
import sys
from pathlib import Path

# __file__ = .../repo/cs2-esp-test/tools/gen_offsets.py
TOOLS_DIR = Path(__file__).resolve().parent          # .../cs2-esp-test/tools
PROJECT_DIR = TOOLS_DIR.parent                       # .../cs2-esp-test
REPO_ROOT = PROJECT_DIR.parent                       # .../repo  (contains the JSONs)
SRC = PROJECT_DIR / "src"

OFFSETS_JSON = REPO_ROOT / "offsets.json"
CLIENT_DLL_JSON = REPO_ROOT / "client_dll.json"
INFO_JSON = REPO_ROOT / "info.json"


def load_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def fmt_ptr(value):
    """Format an offset as a C++ size_t literal."""
    return f"static_cast<std::ptrdiff_t>({value})"


def generate_offsets_hpp(offsets_data, info_data):
    """offsets.hpp: module -> {name: value} (module-relative dw* offsets)."""
    lines = []
    lines.append("// ====================================================================")
    lines.append("// offsets.hpp")
    lines.append("//")
    lines.append("// Module-relative offsets (dw*) extracted from offsets.json")
    lines.append("// (cs2-dumper output, build {build}, timestamp {ts})".format(
        build=info_data.get("build_number", "?"),
        ts=info_data.get("timestamp", "?")))
    lines.append("//")
    lines.append("// NOTE: these are RELATIVE TO THE MODULE BASE ADDRESS. To get the")
    lines.append("// absolute address of a global, do: moduleBase + offset.")
    lines.append("// DO NOT confuse with class field offsets in schema.hpp (those are")
    lines.append("// relative to a class instance base).")
    lines.append("// This file is GENERATED by tools/gen_offsets.py. Do not edit by hand.")
    lines.append("// ====================================================================")
    lines.append("")
    lines.append("#pragma once")
    lines.append("#include <cstddef>")
    lines.append("")
    lines.append("namespace cs2 {")
    lines.append("namespace offsets {")
    lines.append("")

    for mod_name in sorted(offsets_data.keys()):
        entries = offsets_data[mod_name]
        if not isinstance(entries, dict):
            continue
        ns = mod_name.replace(".", "_").replace("-", "_")
        lines.append(f"namespace {ns} {{")
        for name in sorted(entries.keys()):
            val = entries[name]
            if not isinstance(val, int):
                continue
            lines.append(f"    inline constexpr std::ptrdiff_t {name} = {fmt_ptr(val)};")
        lines.append("} // namespace " + ns)
        lines.append("")

    lines.append("} // namespace offsets")
    lines.append("} // namespace cs2")
    lines.append("")
    return "\n".join(lines)


def generate_schema_hpp(client_dll_data):
    """schema.hpp: class -> {field: offset} (relative to class instance base)."""
    classes = {}
    for mod_name, mod_data in client_dll_data.items():
        if not isinstance(mod_data, dict):
            continue
        mod_classes = mod_data.get("classes", {})
        if isinstance(mod_classes, dict):
            classes.update(mod_classes)

    # Only the fields the diagnostic/ESP actually needs, keyed by class name.
    wanted = {
        "C_BaseEntity": [
            "m_pGameSceneNode", "m_iTeamNum", "m_iHealth", "m_iMaxHealth",
            "m_lifeState",
        ],
        "CGameSceneNode": [
            "m_vecAbsOrigin", "m_vecOrigin", "m_bDormant",
        ],
        "CEntityInstance": [
            "m_pEntity",
        ],
        "CCSPlayerController": [
            "m_hPlayerPawn", "m_iPawnHealth", "m_bPawnIsAlive",
        ],
    }

    lines = []
    lines.append("// ====================================================================")
    lines.append("// schema.hpp")
    lines.append("//")
    lines.append("// Class field offsets (m_*) extracted from client_dll.json")
    lines.append("// (cs2-dumper output, client.dll: 542 classes, 14 enums)")
    lines.append("//")
    lines.append("// NOTE: these are RELATIVE TO THE CLASS INSTANCE BASE ADDRESS. To read a")
    lines.append("// field of a live object, do: instanceBase + fieldOffset.")
    lines.append("// DO NOT confuse with module-relative offsets in offsets.hpp.")
    lines.append("// This file is GENERATED by tools/gen_offsets.py. Do not edit by hand.")
    lines.append("// ====================================================================")
    lines.append("")
    lines.append("#pragma once")
    lines.append("#include <cstddef>")
    lines.append("")
    lines.append("namespace cs2 {")
    lines.append("namespace schema {")
    lines.append("")

    for cls_name in sorted(wanted.keys()):
        cls = classes.get(cls_name)
        if not isinstance(cls, dict):
            lines.append(f"// WARNING: class '{cls_name}' not found in client_dll.json!")
            lines.append("")
            continue
        fields = cls.get("fields", {})
        if not isinstance(fields, dict):
            continue
        lines.append(f"namespace {cls_name} {{")
        found_any = False
        for field in wanted[cls_name]:
            if field in fields:
                val = fields[field]
                if isinstance(val, int):
                    lines.append(f"    inline constexpr std::ptrdiff_t {field} = {fmt_ptr(val)};")
                    found_any = True
        if not found_any:
            lines.append(f"    // WARNING: none of the wanted fields found for '{cls_name}'!")
        lines.append("} // namespace " + cls_name)
        lines.append("")

    lines.append("} // namespace schema")
    lines.append("} // namespace cs2")
    lines.append("")
    return "\n".join(lines)


def main():
    for p in (OFFSETS_JSON, CLIENT_DLL_JSON, INFO_JSON):
        if not p.exists():
            print(f"ERROR: required input not found: {p}", file=sys.stderr)
            return 1

    offsets_data = load_json(OFFSETS_JSON)
    client_dll_data = load_json(CLIENT_DLL_JSON)
    info_data = load_json(INFO_JSON)

    SRC.mkdir(parents=True, exist_ok=True)

    offsets_hpp = SRC / "offsets.hpp"
    schema_hpp = SRC / "schema.hpp"

    offsets_hpp.write_text(generate_offsets_hpp(offsets_data, info_data),
                           encoding="utf-8")
    schema_hpp.write_text(generate_schema_hpp(client_dll_data), encoding="utf-8")

    print(f"WROTE {offsets_hpp}")
    print(f"WROTE {schema_hpp}")
    print("Done. Values are sourced directly from the cs2-dumper JSON files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
